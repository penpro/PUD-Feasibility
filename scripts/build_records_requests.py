"""Render public records requests from one YAML source per request.

For each docs/records-requests/<id>.yaml:
  - rewrites the generated block in docs/records-requests/<id>.md (public; blanks instead of personal details)
  - if private/requester.yaml exists: writes, per agency, into private/records-requests/
        <id>_<agency>.tex   LaTeX source
        <id>_<agency>.pdf   the letter (XeLaTeX, MiKTeX on this machine)
        <id>_<agency>_email.txt   To / Subject / ready-to-paste body (full request text, PDF attached)

private/ is gitignored: it holds the requester's name and contact details.

    python scripts/build_records_requests.py            # md + letters
    python scripts/build_records_requests.py --md-only  # md only (no LaTeX needed)
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REQ_DIR = ROOT / "docs" / "records-requests"
PRIVATE = ROOT / "private"
REQUESTER = PRIVATE / "requester.yaml"
OUT_DIR = PRIVATE / "records-requests"

BEGIN = "<!-- BEGIN GENERATED by scripts/build_records_requests.py from the .yaml beside this file. Edit the .yaml, not this block. -->"
END = "<!-- END GENERATED -->"
INLINE = re.compile(r"(\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`)")
MIKTEX_DEFAULT = Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "MiKTeX" / "miktex" / "bin" / "x64"


# ---------------------------------------------------------------- loading

def request_files() -> list[Path]:
    return sorted(p for p in REQ_DIR.glob("*.yaml") if p.name != "requester.example.yaml")


def load_request(path: Path) -> dict:
    req = yaml.safe_load(path.read_text(encoding="utf-8"))
    fee = str(req["fee_limit"])
    fill = lambda s: s.replace("{fee_limit}", fee)  # noqa: E731
    req["items"] = [fill(s) for s in req["items"]]
    req["closing"] = [fill(s) for s in req["closing"]]
    req["intro"] = fill(req["intro"])
    req["date"] = req["date"] if isinstance(req["date"], dt.date) else dt.date.fromisoformat(str(req["date"]))
    req["_path"] = path
    return req


def load_requester(path: Path = REQUESTER) -> dict | None:
    if not path.exists():
        return None
    r = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    for key in ("name", "email"):
        if not r.get(key) or r[key] in ("Your Name", "you@example.com"):
            sys.exit(f"{path}: fill in '{key}' first")
    r.setdefault("phone", "")
    r["address"] = r.get("address") or []
    return r


def long_date(d: dt.date) -> str:
    return f"{d:%B} {d.day}, {d.year}"


# ---------------------------------------------------------------- inline markup

def tex_escape(s: str) -> str:
    repl = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
            "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(repl.get(c, c) for c in s)


def to_tex(s: str) -> str:
    out = []
    for part in INLINE.split(s):
        if part.startswith("**") and part.endswith("**") and len(part) > 4:
            out.append(r"\textbf{" + tex_escape(part[2:-2]) + "}")
        elif part.startswith("`") and part.endswith("`"):
            out.append(r"{\ttfamily\small\nolinkurl{" + part[1:-1] + "}}")
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            out.append(r"\emph{" + tex_escape(part[1:-1]) + "}")
        else:
            out.append(tex_escape(part))
    return "".join(out)


def to_text(s: str) -> str:
    return INLINE.sub(lambda m: m.group(0).strip("*`"), s)


# ---------------------------------------------------------------- markdown block (public)

def render_md_block(req: dict) -> str:
    L = [BEGIN, "## Where to send it", "",
         "| Priority | Agency | Why they likely hold it | Send to |", "|---|---|---|---|"]
    for a in req["agencies"]:
        mail = ", ".join(a["address"])
        L.append(f"| {a['priority']} | **{a['name']}** | {a['why']} | Email {a['email']}, or the "
                 f"[online portal]({a['portal']}). Mail: {mail}. |")
    L += ["", "Send to both at once; they are independent agencies with independent records.", "",
          "Contact details checked:"]
    L += [f"- {a['name']}: {a['checked']}" for a in req["agencies"]]
    L += ["", "## Request text", "",
          f"> **Re:** {req['re']}\\",  # trailing backslash = hard line break on GitHub
          "> **To:** Public Records Officer, [AGENCY]\\",
          "> **From:** [YOUR NAME], [AFFILIATION]\\",
          "> **Contact:** [YOUR EMAIL]\\",
          "> **Date:** [DATE]", ">",
          f"> {req['intro']}", ">"]
    for a in req["agencies"]:
        L.append(f"> *In the letter to {a['name']}:* {a['scope']}")
        L.append(">")
    L += [f"> {i}. {item}" for i, item in enumerate(req["items"], 1)]
    L.append(">")
    for para in req["closing"]:
        L += [f"> {para}", ">"]
    L += ["> [YOUR NAME]", END]
    return "\n".join(L)


def splice_md(md: str, block: str, where: str) -> str:
    if BEGIN not in md or END not in md:
        raise SystemExit(f"{where}: missing generated-block markers")
    head, rest = md.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def md_path(req: dict) -> Path:
    return req["_path"].with_suffix(".md")


# ---------------------------------------------------------------- letter (LaTeX)

TEX = r"""\documentclass[11pt,letterpaper]{article}
\usepackage[margin=1in,top=0.85in,bottom=0.9in]{geometry}
\usepackage{fontspec}
% Lining figures matter here (statute numbers, ZIP codes); Georgia's old-style digits read badly.
\IfFontExistsTF{Cambria}{\setmainfont{Cambria}}{\IfFontExistsTF{TeX Gyre Termes}{\setmainfont{TeX Gyre Termes}}{}}
\usepackage{enumitem}
\usepackage{lastpage}
\usepackage{fancyhdr}
\usepackage{xcolor}
\usepackage{url}
\usepackage[hidelinks,pdftitle={<<PDFTITLE>>},pdfauthor={<<NAME>>}]{hyperref}
\urlstyle{same}
\def\UrlBreaks{\do\.\do\_\do\/\do\-}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0.55em}
\setlength{\emergencystretch}{3em}
\raggedright
\pagestyle{fancy}\fancyhf{}\renewcommand{\headrulewidth}{0pt}
\cfoot{\footnotesize\color{black!60}Public records request, <<NAME>>, <<DATE>> \quad Page \thepage\ of \pageref{LastPage}}
\begin{document}
{\Large\bfseries <<NAME>>}\par\vspace{0.15em}
{\small <<CONTACT>>}\par\vspace{0.2em}
{\color{black!35}\rule{\linewidth}{0.6pt}}\par\vspace{0.8em}
<<DATE>>\par\vspace{0.6em}
<<ADDRESS>>\\
By email: \href{mailto:<<AGENCY_EMAIL>>}{<<AGENCY_EMAIL>>}\par\vspace{0.6em}
\textbf{Re: <<RE>>}\par\vspace{0.3em}
Dear Public Records Officer:

<<INTRO>>

<<SCOPE>>

\begin{enumerate}[leftmargin=1.7em,itemsep=0.3em,topsep=0.2em]
<<ITEMS>>
\end{enumerate}

<<CLOSING>>

Sincerely,\par\vspace{0.8em}
<<NAME>>\\
<<SIGNATURE>>
\end{document}
"""


def render_tex(req: dict, agency: dict, who: dict) -> str:
    contact = [r"\href{mailto:%s}{%s}" % (who["email"], tex_escape(who["email"]))]
    if who.get("phone"):
        contact.append(tex_escape(who["phone"]))
    contact += [tex_escape(x) for x in who["address"]]
    sig = []
    if who.get("affiliation"):
        sig.append(tex_escape(who["affiliation"]))
    if who.get("affiliation_url"):
        sig.append(r"\url{%s}" % who["affiliation_url"])
    sig.append(r"\href{mailto:%s}{%s}" % (who["email"], tex_escape(who["email"])))
    if who.get("phone"):
        sig.append(tex_escape(who["phone"]))
    fields = {
        "PDFTITLE": tex_escape(f"Public records request to {agency['name']}"),
        "NAME": tex_escape(who["name"]),
        "CONTACT": r" \quad\textperiodcentered\quad ".join(contact),
        "DATE": long_date(req["date"]),
        "ADDRESS": r"\\".join(tex_escape(x) for x in agency["address"]),
        "AGENCY_EMAIL": agency["email"],
        "RE": to_tex(req["re"]),
        "INTRO": to_tex(req["intro"]),
        "SCOPE": to_tex(agency["scope"]),
        "ITEMS": "\n".join(r"\item " + to_tex(x) for x in req["items"]),
        "CLOSING": "\n\n".join(to_tex(x) for x in req["closing"]),
        "SIGNATURE": r"\\".join(sig),
    }
    out = TEX
    for k, v in fields.items():
        out = out.replace(f"<<{k}>>", v)
    leftover = re.findall(r"<<[A-Z_]+>>", out)
    assert not leftover, leftover
    return out


# ---------------------------------------------------------------- email (plain text)

def render_email(req: dict, agency: dict, who: dict, pdf_name: str) -> str:
    sig = [who["name"]] + [x for x in (who.get("affiliation"), who.get("affiliation_url"), who["email"],
                                       who.get("phone")) if x]
    opener = "Please accept the public records request below. The same request is attached as a PDF."
    if agency.get("email_note"):
        opener += " " + agency["email_note"]
    body = [
        "Dear Public Records Officer,", "", opener, "",
        f"Re: {to_text(req['re'])}", "",
        to_text(req["intro"]), "",
        to_text(agency["scope"]), "",
        # one paragraph per item and per closing line, so they survive any mail client's reflow
        *[p for i, x in enumerate(req["items"], 1) for p in (f"{i}. {to_text(x)}", "")],
        *[p for x in req["closing"] for p in (to_text(x), "")],
        "Sincerely,", *sig,
    ]
    head = [
        f"TO:       {agency['email']}",
        f"SUBJECT:  {req['email_subject']}",
        f"ATTACH:   {pdf_name}",
        f"(Portal instead of email, if you prefer: {agency['portal']})",
        "",
        "----- copy everything below this line into the email body -----",
        "",
    ]
    return "\n".join(head + body) + "\n"


# ---------------------------------------------------------------- build

def xelatex() -> str:
    found = shutil.which("xelatex") or (str(MIKTEX_DEFAULT / "xelatex.exe")
                                        if (MIKTEX_DEFAULT / "xelatex.exe").exists() else None)
    if not found:
        sys.exit("xelatex not found: install MiKTeX or TeX Live, or run with --md-only")
    return found


def compile_pdf(tex_path: Path) -> Path:
    build = tex_path.parent / ".build"
    build.mkdir(exist_ok=True)
    env = dict(os.environ)
    # A PATH entry that is a file (not a directory) breaks MiKTeX's tool lookup on this machine.
    env["PATH"] = os.pathsep.join(p for p in env.get("PATH", "").split(os.pathsep)
                                  if p and not p.lower().endswith(".exe"))
    cmd = [xelatex(), "-interaction=nonstopmode", "-halt-on-error", f"-output-directory={build}", str(tex_path)]
    for _ in range(2):  # second pass resolves "Page x of y"
        res = subprocess.run(cmd, cwd=build, env=env, capture_output=True, text=True,
                             encoding="utf-8", errors="replace")
        if res.returncode != 0:
            log = (build / tex_path.with_suffix(".log").name)
            tail = log.read_text(encoding="utf-8", errors="replace")[-3000:] if log.exists() else res.stdout[-3000:]
            sys.exit(f"xelatex failed on {tex_path.name}:\n{tail}")
    pdf = tex_path.with_suffix(".pdf")
    shutil.copyfile(build / pdf.name, pdf)
    return pdf


def build(md_only: bool = False) -> list[Path]:
    written = []
    who = None if md_only else load_requester()
    for path in request_files():
        req = load_request(path)
        mdp = md_path(req)
        md = mdp.read_text(encoding="utf-8")
        new = splice_md(md, render_md_block(req), str(mdp))
        if new != md:
            mdp.write_text(new, encoding="utf-8", newline="\n")
            written.append(mdp)
        if who is None:
            continue
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for a in req["agencies"]:
            stem = f"{req['id']}_{a['id']}"
            tex = OUT_DIR / f"{stem}.tex"
            tex.write_text(render_tex(req, a, who), encoding="utf-8", newline="\n")
            pdf = compile_pdf(tex)
            mail = OUT_DIR / f"{stem}_email.txt"
            mail.write_text(render_email(req, a, who, pdf.name), encoding="utf-8", newline="\n")
            written += [tex, pdf, mail]
    if not md_only and who is None:
        print(f"No {REQUESTER.relative_to(ROOT)}: copy docs/records-requests/requester.example.yaml there "
              "to build the PDF letters. Markdown updated only.")
    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--md-only", action="store_true", help="update the public .md block only")
    args = ap.parse_args()
    for p in build(args.md_only):
        print("wrote", p.relative_to(ROOT))


if __name__ == "__main__":
    main()
