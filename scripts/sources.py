"""Source registry tool.

    python scripts/sources.py build    # regenerate data/SOURCES.md + data/raw/MANIFEST.sha256
    python scripts/sources.py verify   # check every raw file is registered and unchanged

Rules enforced (the point of this script):
  * every file under data/raw/ is claimed by exactly one source in data/sources.yaml
  * every file a source claims actually exists
  * every file's SHA-256 matches the manifest (verify mode), so silent edits to "untouched"
    raw files are caught
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
REGISTRY = ROOT / "data" / "sources.yaml"
MANIFEST = RAW / "MANIFEST.sha256"
SOURCES_MD = ROOT / "data" / "SOURCES.md"
KINDS = {"primary", "secondary", "third-party", "advocacy"}
REQUIRED = ("id", "title", "publisher", "kind", "url", "accessed", "files", "notes")


def load_registry() -> list[dict]:
    data = yaml.safe_load(REGISTRY.read_text(encoding="utf-8"))
    return data["sources"]


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def resolve(sources: list[dict]) -> tuple[dict[str, str], list[str]]:
    """Map each raw file (repo-relative posix path) -> source id. Return (mapping, problems)."""
    problems: list[str] = []
    owner: dict[str, str] = {}
    seen_ids: set[str] = set()
    for s in sources:
        for k in REQUIRED:
            if k not in s:
                problems.append(f"{s.get('id', '?')}: missing field '{k}'")
        sid = s.get("id", "?")
        if sid in seen_ids:
            problems.append(f"{sid}: duplicate id")
        seen_ids.add(sid)
        if s.get("kind") not in KINDS:
            problems.append(f"{sid}: kind must be one of {sorted(KINDS)}")
        files = s.get("files") or []
        if not files and not s.get("archive_note"):
            problems.append(f"{sid}: no files and no archive_note explaining why")
        for pattern in files:
            matches = sorted(ROOT.glob(pattern))
            if not matches:
                problems.append(f"{sid}: claimed file/glob matches nothing: {pattern}")
            for m in matches:
                r = rel(m)
                if r in owner and owner[r] != sid:
                    problems.append(f"{r}: claimed by both {owner[r]} and {sid}")
                owner[r] = sid
    on_disk = {rel(p) for p in RAW.rglob("*") if p.is_file() and p != MANIFEST}
    for r in sorted(on_disk - owner.keys()):
        problems.append(f"{r}: file in data/raw/ is not registered in data/sources.yaml")
    return owner, problems


def render_markdown(sources: list[dict], owner: dict[str, str], hashes: dict[str, str]) -> str:
    out = [
        "# Sources",
        "",
        "<!-- GENERATED by scripts/sources.py from data/sources.yaml. Do not edit by hand. -->",
        "",
        "Every number in this study cites one of these IDs. Files under `data/raw/` are",
        "unmodified copies; their SHA-256 hashes are in `data/raw/MANIFEST.sha256`.",
        "",
        "Source kinds: **primary** (the producer of the number), **secondary** (journalism),",
        "**third-party** (aggregator with undisclosed method), **advocacy** (a party to the debate).",
        "",
        "| ID | Source | Publisher | Kind | Accessed |",
        "|---|---|---|---|---|",
    ]
    for s in sources:
        out.append(f"| {s['id']} | [{s['title']}]({s['url']}) | {s['publisher']} | {s['kind']} | {s['accessed']} |")
    out.append("")
    for s in sources:
        out += [f"## {s['id']} — {s['title']}", ""]
        out.append(f"- **Publisher:** {s['publisher']}")
        out.append(f"- **Kind:** {s['kind']}")
        out.append(f"- **URL:** <{s['url']}>")
        out.append(f"- **Accessed:** {s['accessed']}")
        files = sorted(r for r, sid in owner.items() if sid == s["id"])
        if files:
            out.append("- **Files:**")
            for r in files:
                out.append(f"  - `{r}` (sha256 `{hashes[r][:12]}…`)")
        else:
            out.append(f"- **Files:** none archived. {s.get('archive_note', '')}")
        out.append(f"- **Notes:** {s['notes']}")
        out.append("")
    return "\n".join(out)


def build() -> int:
    sources = load_registry()
    owner, problems = resolve(sources)
    if problems:
        print("Registry problems:\n  " + "\n  ".join(problems))
        return 1
    hashes = {r: sha256(ROOT / r) for r in sorted(owner)}
    MANIFEST.write_text("".join(f"{h}  {r}\n" for r, h in hashes.items()), encoding="utf-8", newline="\n")
    SOURCES_MD.write_text(render_markdown(sources, owner, hashes), encoding="utf-8", newline="\n")
    print(f"OK: {len(sources)} sources, {len(hashes)} raw files hashed -> {rel(MANIFEST)}, {rel(SOURCES_MD)}")
    return 0


def verify() -> int:
    sources = load_registry()
    owner, problems = resolve(sources)
    if not MANIFEST.exists():
        problems.append("data/raw/MANIFEST.sha256 missing: run `python scripts/sources.py build`")
    else:
        recorded = {}
        for line in MANIFEST.read_text(encoding="utf-8").splitlines():
            h, r = line.split("  ", 1)
            recorded[r] = h
        for r in sorted(owner):
            if r not in recorded:
                problems.append(f"{r}: not in manifest (run build)")
            elif sha256(ROOT / r) != recorded[r]:
                problems.append(f"{r}: SHA-256 changed since manifest was built (raw files must stay untouched)")
        for r in sorted(recorded.keys() - owner.keys()):
            problems.append(f"{r}: in manifest but no longer present/registered")
    if problems:
        print("FAIL:\n  " + "\n  ".join(problems))
        return 1
    print(f"OK: {len(owner)} raw files verified against manifest")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["build", "verify"])
    args = ap.parse_args(argv)
    return build() if args.command == "build" else verify()


if __name__ == "__main__":
    sys.exit(main())
